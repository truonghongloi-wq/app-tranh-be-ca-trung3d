/// Vẽ icon duotone: mảng nền mờ 20% phía dưới, nét chính đậm phía trên.
class DuotoneIcon extends StatelessWidget {
  final DuotoneGlyph glyph;
  final double size;
  final Color color;
  const DuotoneIcon(
    this.glyph, {
    super.key,
    required this.size,
    required this.color,
  });

  @override
  Widget build(BuildContext context) => Stack(
    children: [
      Icon(glyph.$2, size: size, color: color.withValues(alpha: 0.2)),
      Icon(glyph.$1, size: size, color: color),
    ],
  );
}

/// Dao rọc giấy (cutter) — bộ Phosphor không có nên vẽ tay theo đúng quy
/// cách duotone của Phosphor: lưới 24×24, nét 1.5, bo tròn đầu/góc, mảng
/// nền mờ 20%. Đặt chéo 45° (cán dưới trái, lưỡi trên phải).
class BoxCutterIcon extends StatelessWidget {
  final double size;
  final Color color;
  const BoxCutterIcon({super.key, required this.size, required this.color});

  @override
  Widget build(BuildContext context) => SizedBox(
    width: size,
    height: size,
    child: CustomPaint(painter: _BoxCutterPainter(color)),
  );
}

class _BoxCutterPainter extends CustomPainter {
  final Color color;
  const _BoxCutterPainter(this.color);

  @override
  void paint(Canvas canvas, Size size) {
    final k = size.width / 24;
    canvas.scale(k);
    // Xoay quanh tâm để dao nằm chéo từ dưới trái lên trên phải
    canvas.translate(12, 12);
    canvas.rotate(-0.785398); // -45°
    canvas.translate(-12, -12);

    final stroke = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.5
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;
    final fill = Paint()..color = color.withValues(alpha: 0.2);

    // Cán dao
    final handle = RRect.fromLTRBR(1, 9, 14, 15, const Radius.circular(1.5));
    // Lưỡi dao: hình thang, mũi vát ở cuối
    final blade = Path()
      ..moveTo(14, 10)
      ..lineTo(20, 10)
      ..lineTo(23.25, 14)
      ..lineTo(14, 14)
      ..close();

    canvas.drawRRect(handle, fill);
    canvas.drawRRect(handle, stroke);
    canvas.drawPath(blade, stroke);
    // Vạch bẻ lưỡi (song song mũi dao)
    canvas.drawLine(const Offset(16.6, 10.6), const Offset(18.4, 13.4), stroke);
    // Nút đẩy lưỡi trên cán
    canvas.drawLine(const Offset(5.5, 12), const Offset(9, 12), stroke);
  }

  @override
  bool shouldRepaint(_BoxCutterPainter old) => old.color != color;
}
